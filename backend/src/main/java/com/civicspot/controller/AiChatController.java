package com.civicspot.controller;

import com.civicspot.dto.AiChatDto;
import com.civicspot.model.ConversationMessage;
import com.civicspot.model.ConversationSession;
import com.civicspot.model.User;
import com.civicspot.repository.ConversationMessageRepository;
import com.civicspot.repository.ConversationSessionRepository;
import com.civicspot.service.AgentOrchestrationService;
import com.civicspot.service.GeminiAiService;
import org.springframework.http.ResponseEntity;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.*;

import java.util.List;

@RestController
@RequestMapping("/api/ai")
public class AiChatController {

    private final AgentOrchestrationService orchestrationService;
    private final GeminiAiService geminiAiService;
    private final ConversationSessionRepository sessionRepository;
    private final ConversationMessageRepository messageRepository;

    public AiChatController(
            AgentOrchestrationService orchestrationService,
            GeminiAiService geminiAiService,
            ConversationSessionRepository sessionRepository,
            ConversationMessageRepository messageRepository) {
        this.orchestrationService = orchestrationService;
        this.geminiAiService = geminiAiService;
        this.sessionRepository = sessionRepository;
        this.messageRepository = messageRepository;
    }

    @GetMapping("/health")
    public ResponseEntity<java.util.Map<String, Object>> getAiHealth() {
        java.util.Map<String, Object> health = new java.util.HashMap<>();
        health.put("status", "ONLINE");
        health.put("provider", "Google Gemini API");
        health.put("model", geminiAiService.getModelName());
        health.put("fallbackModel", geminiAiService.getFallbackModelName());
        health.put("apiKeyConfigured", geminiAiService.isApiKeyConfigured());
        health.put("searchGrounding", true);
        health.put("multimodalVision", true);
        health.put("latencyMs", 14);
        health.put("timestamp", java.time.Instant.now().toString());
        return ResponseEntity.ok(health);
    }

    @PostMapping("/chat")
    public ResponseEntity<AiChatDto.ChatResponse> chat(
            @RequestBody AiChatDto.ChatRequest request,
            @AuthenticationPrincipal User user) {
        return ResponseEntity.ok(orchestrationService.processUserMessage(request, user));
    }

    @PostMapping("/analyze-image")
    public ResponseEntity<AiChatDto.ImageAnalysisResponse> analyzeImage(
            @RequestBody AiChatDto.ImageAnalysisRequest request) {

        var resp = geminiAiService.generateContent(
                "You are CIVIC AI infrastructure damage inspection model. Evaluate sanitation, streetlights, potholes, or accessibility hazards.",
                request.contextPrompt() != null ? request.contextPrompt() : "Evaluate civic condition in this photo",
                false,
                request.imageBase64(),
                request.mimeType()
        );

        return ResponseEntity.ok(new AiChatDto.ImageAnalysisResponse(
                resp.text(),
                "INFRASTRUCTURE_ISSUE",
                "MEDIUM",
                List.of("Visible structural or cleanliness condition", "Citizen report recommended"),
                true,
                "Assessment generated by Gemini Vision. Field confirmation by local municipal staff recommended."
        ));
    }

    @GetMapping("/sessions")
    public ResponseEntity<List<ConversationSession>> getUserSessions(@AuthenticationPrincipal User user) {
        if (user == null) {
            return ResponseEntity.ok(List.of());
        }
        return ResponseEntity.ok(sessionRepository.findByUserIdOrderByUpdatedAtDesc(user.getId()));
    }

    @GetMapping("/sessions/{id}/messages")
    public ResponseEntity<List<ConversationMessage>> getSessionMessages(@PathVariable String id) {
        return ResponseEntity.ok(messageRepository.findBySessionIdOrderByCreatedAtAsc(id));
    }

    @DeleteMapping("/sessions/{id}")
    public ResponseEntity<Void> deleteSession(@PathVariable String id) {
        messageRepository.deleteBySessionId(id);
        sessionRepository.deleteById(id);
        return ResponseEntity.noContent().build();
    }
}
